// 데이터 구조가 올바른지 간단히 검증하는 함수입니다.
function validateUniversityData() {
  const validRegions = [
    "서울특별시",
    "부산광역시",
    "대구광역시",
    "인천광역시",
    "광주광역시",
    "대전광역시",
    "울산광역시",
    "세종특별자치시",
    "경기도",
    "강원특별자치도",
    "충청북도",
    "충청남도",
    "전북특별자치도",
    "전라남도",
    "경상북도",
    "경상남도",
    "제주특별자치도",
  ];

  const seenIds = new Set();
  const errors = [];

  universities.forEach((university) => {
    if (!university.id) {
      errors.push(`id가 없는 학교: ${university.name || "이름 없음"}`);
    } else if (seenIds.has(university.id)) {
      errors.push(`중복된 id: ${university.id}`);
    } else {
      seenIds.add(university.id);
    }

    if (!university.name) {
      errors.push("학교 이름이 없는 데이터가 있습니다.");
    }

    if (!university.address) {
      errors.push(`주소가 없는 학교: ${university.name || "이름 없음"}`);
    }

    if (!validRegions.includes(university.region)) {
      errors.push(`region 값이 올바르지 않음: ${university.name || "이름 없음"}`);
    }

    if (!["국립", "공립", "사립"].includes(university.type)) {
      errors.push(`type 값이 올바르지 않음: ${university.name || "이름 없음"}`);
    }

    if (typeof university.lat !== "number" || typeof university.lng !== "number") {
      errors.push(`좌표가 숫자가 아님: ${university.name || "이름 없음"}`);
    } else {
      if (university.lat < 32 || university.lat > 39 || university.lng < 124 || university.lng > 132) {
        errors.push(`대한민국 범위를 벗어난 좌표: ${university.name || "이름 없음"}`);
      }
    }

    if (!university.website || !/^https?:\/\//.test(university.website)) {
      errors.push(`홈페이지 주소 형식이 잘못됨: ${university.name || "이름 없음"}`);
    }
  });

  if (errors.length > 0) {
    console.warn("대학교 데이터 검증 경고:", errors);
  } else {
    console.log(`대학교 데이터 검증 완료: 총 ${universities.length}개 캠퍼스`);
  }
}

universities.forEach((university) => {
  const campusNames = {
    "korea-university-seoul": "서울캠퍼스",
    "korea-university-sejong-campus-분교": "세종캠퍼스",
    "yonsei-university-sinchon": "신촌캠퍼스",
    "yonsei-university-mirae-campus-분교": "미래캠퍼스",
    "hanyang-university-seoul": "서울캠퍼스",
    "hanyang-university-erica-campus-분교": "ERICA캠퍼스"
  };
  if (campusNames[university.id]) university.campusName = campusNames[university.id];
  if (!university.campusName) university.campusName = university.campusType || "캠퍼스";
  if (!university.universityGroupId) university.universityGroupId = university.id;
  if (university.id.startsWith("hanyang-university-")) university.universityGroupId = "hanyang-university";
  if (university.id.startsWith("korea-university-") && university.id !== "korea-university-of-technology-and-education") university.universityGroupId = "korea-university";
  if (university.id.startsWith("yonsei-university-")) university.universityGroupId = "yonsei-university";
  if (university.id === "ewha-womans-university") university.universityGroupId = "ewha-womans-university";
  if (university.id === "korea-university-of-technology-and-education") university.universityGroupId = "koreatech";
  const officialEmblem = university.logo
    ? { file: university.logo, source: university.logoSource || university.website || "" }
    : university.id.startsWith("hanyang-university-")
      ? { file: "assets/university-emblems/hanyang-university.png", source: "https://www.hanyang.ac.kr/symbol-logo" }
      : university.id.startsWith("korea-university-") && university.id !== "korea-university-of-technology-and-education"
        ? { file: "assets/university-emblems/korea-university.gif", source: "https://www.korea.ac.kr/ko/373/subview.do" }
        : university.id.startsWith("yonsei-university-")
          ? { file: "assets/university-emblems/yonsei-university.png", source: "https://www.yonsei.ac.kr/sc/336/subview.do" }
          : university.id === "ewha-womans-university"
            ? { file: "assets/university-emblems/ewha-womans-university.png", source: "https://www.ewha.ac.kr/ewha/intro/ui-si01.do" }
            : university.id === "korea-university-of-technology-and-education"
              ? { file: "assets/university-emblems/korea-university-of-technology-and-education.gif", source: "https://www.koreatech.ac.kr/menu.es?mid=a10101030100" }
      : null;
  university.emblem = officialEmblem ? officialEmblem.file : "assets/university-emblems/placeholder-emblem.svg";
  university.emblemSource = officialEmblem ? officialEmblem.source : "";
  university.emblemStatus = officialEmblem ? "verified" : "missing";
  university.emblemVerifiedAt = "2026-08-04";
});

validateUniversityData();

